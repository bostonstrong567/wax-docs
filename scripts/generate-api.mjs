const sources = fs
  .readdirSync(TYPES)
  .filter((name) => name.endsWith('.lua') && !SKIP.has(name))
  .sort((a, b) => {
    const order = Object.keys(PAGES);
    const [ia, ib] = [order.indexOf(a), order.indexOf(b)];
    return (ia === -1 ? order.length : ia) - (ib === -1 ? order.length : ib) || a.localeCompare(b);
  });

const models = sources.map((name) => parseFile(name, fs.readFileSync(path.join(TYPES, name), 'utf8')));
const files = build(models);

fs.mkdirSync(OUT, { recursive: true });
let written = 0;
for (const [name, content] of files) {
  const target = path.join(OUT, name);
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === content) continue;
  fs.writeFileSync(target, content);
  written++;
}
// A generated page whose type file is gone goes too; hand-written pages are left alone.
for (const name of fs.readdirSync(OUT)) {
  if (!name.endsWith('.mdx') || files.has(name)) continue;
  const target = path.join(OUT, name);
  if (fs.readFileSync(target, 'utf8').includes(MARKER)) {
    fs.rmSync(target);
    console.log(`[generate-api] removed ${name} (its type file no longer exists)`);
  }
}

const count = (pick) => models.reduce((sum, model) => sum + pick(model), 0);
console.log(
  `[generate-api] ${files.size} pages from ${sources.join(', ')}: ` +
    `${count((m) => m.classes.length)} classes, ` +
    `${count((m) => m.functions.length + m.classes.reduce((n, c) => n + c.methods.length, 0))} functions, ` +
    `${count((m) => m.aliases.length)} aliases; ${written} file(s) changed.`,
);
if (SKIP.size) console.log(`[generate-api] skipped on purpose: ${[...SKIP].join(', ')}`);
if (bare.length) console.log(`[generate-api] ${bare.length} class(es) or function(s) have no description in the type files: ${bare.join(', ')}`);
if (notes.length) {
  console.log(`[generate-api] ${notes.length} thing(s) could not be used as written:`);
  for (const line of notes) console.log(`  ${line}`);
}
